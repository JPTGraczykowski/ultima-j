/// Glyph table size: ASCII plus Latin Extended-A, which holds the Polish letters.
const GLYPH_SLOTS: usize = 0x180;

impl Font {
    pub fn small() -> Font {
        let mut glyphs: Vec<Option<Glyph>> = vec![None; GLYPH_SLOTS];
        for (ch, rows) in SMALL_GLYPHS {
            let w = rows[0].len() as i32;
            let mut mask = vec![false; (w * 6) as usize];
            for (y, row) in rows.iter().enumerate() {
                debug_assert_eq!(row.len() as i32, w, "glyph {:?} row width", ch);
                for (x, c) in row.chars().enumerate() {
                    mask[y * w as usize + x] = c == '#';
                }
            }
            glyphs[*ch as usize] = Some(Glyph { w, mask });
        }
        Font { glyphs, height: 6, spacing: 1, space_w: 3, line_h: 6 }
    }

    /// Derive a 2x font with EPX (Scale2x) smoothing.
    pub fn scale2x(&self) -> Font {
        let h = self.height;
        let glyphs = self
            .glyphs
            .iter()
            .map(|g| {
                g.as_ref().map(|g| {
                    let get = |x: i32, y: i32| -> bool {
                        if x < 0 || y < 0 || x >= g.w || y >= h { false } else { g.mask[(y * g.w + x) as usize] }
                    };
                    let w2 = g.w * 2;
                    let mut m = vec![false; (w2 * h * 2) as usize];
                    for y in 0..h {
                        for x in 0..g.w {
                            let p = get(x, y);
                            let a = get(x, y - 1);
                            let b = get(x + 1, y);
                            let c = get(x - 1, y);
                            let d = get(x, y + 1);
                            let mut e = [p; 4];
                            if c == a && c != d && a != b {
                                e[0] = a;
                            }
                            if a == b && a != c && b != d {
                                e[1] = b;
                            }
                            if d == c && d != b && c != a {
                                e[2] = c;
                            }
                            if b == d && b != a && d != c {
                                e[3] = d;
                            }
                            let i0 = ((y * 2) * w2 + x * 2) as usize;
                            let i1 = ((y * 2 + 1) * w2 + x * 2) as usize;
                            m[i0] = e[0];
                            m[i0 + 1] = e[1];
                            m[i1] = e[2];
                            m[i1 + 1] = e[3];
                        }
                    }
                    Glyph { w: w2, mask: m }
                })
            })
            .collect();
        Font {
            glyphs,
            height: h * 2,
            spacing: self.spacing * 2,
            space_w: self.space_w * 2,
            line_h: self.line_h * 2,
        }
    }

    fn glyph(&self, ch: char) -> Option<&Glyph> {
        let i = ch as usize;
        self.glyphs.get(i).and_then(|g| g.as_ref()).or(self.glyphs['?' as usize].as_ref())
    }

    #[cfg(test)]
    pub fn has_glyph(&self, ch: char) -> bool {
        self.glyphs.get(ch as usize).map(|g| g.is_some()).unwrap_or(false)
    }

    pub fn char_width(&self, ch: char) -> i32 {
        if ch == ' ' {
            return self.space_w;
        }
        self.glyph(ch).map(|g| g.w).unwrap_or(self.space_w)
    }

    pub fn text_width(&self, s: &str) -> i32 {
        let mut w = 0;
        for (i, ch) in s.chars().enumerate() {
            if i > 0 {
                w += self.spacing;
            }
            w += self.char_width(ch);
        }
        w
    }

    /// Draw text in a single colour. Returns the x after the last glyph.
    pub fn draw(&self, dst: &mut Bitmap, x: i32, y: i32, s: &str, col: u8) -> i32 {
        self.draw_rows(dst, x, y, s, &[col])
    }

    /// Draw text where each pixel row may have its own colour (gradients).
    /// `cols` is indexed by glyph row (clamped to the last entry).
    pub fn draw_rows(&self, dst: &mut Bitmap, x: i32, y: i32, s: &str, cols: &[u8]) -> i32 {
        let mut cx = x;
        for ch in s.chars() {
            if ch == ' ' {
                cx += self.space_w + self.spacing;
                continue;
            }
            if let Some(g) = self.glyph(ch) {
                for gy in 0..self.height {
                    let col = cols[(gy as usize).min(cols.len() - 1)];
                    for gx in 0..g.w {
                        if g.mask[(gy * g.w + gx) as usize] {
                            dst.set(cx + gx, y + gy, col);
                        }
                    }
                }
                cx += g.w + self.spacing;
            } else {
                cx += self.space_w + self.spacing;
            }
        }
        cx - self.spacing
    }

    /// Text with a full 1-pixel outline and a vertical colour gradient.
    pub fn draw_fancy(&self, dst: &mut Bitmap, x: i32, y: i32, s: &str, cols: &[u8], outline: u8, shadow: Option<u8>) -> i32 {
        let w = self.text_width(s) + 4;
        let mut tmp = Bitmap::new(w, self.height + 4);
        self.draw_rows(&mut tmp, 2, 2, s, cols);
        let o = tmp.outlined(outline, false);
        if let Some(sh) = shadow {
            dst.blit_silhouette(&o, x - 2 + 1, y - 2 + 1, sh);
        }
        dst.blit(&o, x - 2, y - 2);
        x + w - 4
    }

    pub fn draw_centered(&self, dst: &mut Bitmap, cx: i32, y: i32, s: &str, col: u8) {
        let w = self.text_width(s);
        self.draw(dst, cx - w / 2, y, s, col);
    }

    /// Word-wrap text to a pixel width. Explicit '\n' forces a break.
    pub fn wrap(&self, s: &str, width: i32) -> Vec<String> {
        let mut lines = Vec::new();
        for para in s.split('\n') {
            let mut line = String::new();
            for word in para.split(' ') {
                if word.is_empty() {
                    if !line.is_empty() {
                        line.push(' ');
                    }
                    continue;
                }
                let candidate = if line.is_empty() { word.to_string() } else { format!("{} {}", line, word) };
                if self.text_width(&candidate) <= width || line.is_empty() {
                    line = candidate;
                } else {
                    lines.push(std::mem::take(&mut line));
                    line = word.to_string();
                }
            }
            lines.push(line);
        }
        lines
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn small_font_metrics() {
        let f = Font::small();
        assert_eq!(f.char_width('A'), 4);
        assert_eq!(f.text_width("AB"), 9);
        assert!(f.glyph('g').is_some());
        for (ch, rows) in SMALL_GLYPHS {
            let w = rows[0].len();
            assert!(rows.iter().all(|r| r.len() == w), "glyph {:?} has ragged rows", ch);
        }
    }

    #[test]
    fn wrap_breaks_lines() {
        let f = Font::small();
        let lines = f.wrap("You see a somewhat used torch and a loaf of bread.", 60);
        assert!(lines.len() > 1);
        for l in &lines {
            assert!(f.text_width(l) <= 60 || !l.contains(' '));
        }
    }

    #[test]
    fn scale2x_doubles() {
        let f = Font::small().scale2x();
        assert_eq!(f.height, 12);
        assert_eq!(f.char_width('A'), 8);
    }
}

